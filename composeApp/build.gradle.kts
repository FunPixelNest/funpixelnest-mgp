// ---------- Backend configuration ----------
// Read from environment variables (CI) or local.properties (your machine). Never commit real keys.
// Empty SUPABASE_URL = the app runs on the built-in demo backend.
val localProps = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}
fun configValue(key: String, default: String = ""): String =
    System.getenv(key)?.takeIf { it.isNotBlank() } ?: localProps.getProperty(key)?.takeIf { it.isNotBlank() } ?: default

val backendConfigValues = linkedMapOf(
    "SUPABASE_URL" to configValue("SUPABASE_URL"),
    "SUPABASE_ANON_KEY" to configValue("SUPABASE_ANON_KEY"),
    // Where WebGL game builds are served from (Cloudflare R2 later). Relative = same host as the web app.
    "GAMES_BASE_URL" to configValue("GAMES_BASE_URL", "games/"),
    "FIREBASE_PROJECT_ID" to configValue("FIREBASE_PROJECT_ID"),
    "FIREBASE_API_KEY" to configValue("FIREBASE_API_KEY"),
    "FIREBASE_ANDROID_APP_ID" to configValue("FIREBASE_ANDROID_APP_ID"),
    "FIREBASE_SENDER_ID" to configValue("FIREBASE_SENDER_ID"),
)

val generateBackendConfig by tasks.registering {
    val values = backendConfigValues
    val outDir = layout.buildDirectory.dir("generated/backendConfig/kotlin")
    inputs.properties(values)
    outputs.dir(outDir)
    doLast {
        fun literal(value: String) = "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
        val body = values.entries.joinToString("\n") { (key, value) -> "    const val $key: String = ${literal(value)}" }
        val file = outDir.get().file("com/funpixelnest/mgp/config/BackendConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            "package com.funpixelnest.mgp.config\n\n" +
                "/** Generated by Gradle from env vars / local.properties. Do not edit. */\n" +
                "object BackendConfig {\n$body\n}\n",
        )
    }
}

